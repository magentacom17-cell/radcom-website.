export const getOfficialLogoUrl = (domain?: string): string => {
  if (!domain) return '';
  // Check if we have a locally downloaded verified official file
  if (officialLocalLogos[domain]) {
    return officialLocalLogos[domain];
  }
  // Primary: Google's direct 128px high-resolution favicon / corporate logo service
  return `https://t2.gstatic.com/faviconV2?client=SOCIAL&type=FAV&fallback_opts=TYPE,SIZE,URL&url=https://${domain}&size=128`;
};

export const getSecondaryLogoUrl = (domain?: string): string => {
  if (!domain) return '';
  return `https://www.google.com/s2/favicons?domain=${domain}&sz=128`;
};

export const getTertiaryLogoUrl = (domain?: string): string => {
  if (!domain) return '';
  return `https://unavatar.io/${domain}`;
};
